export function survivalWave(n: number): SpawnEvent[] {
  const t0 = 14;
  const count = 5 + n * 2;
  const gap = Math.max(0.45, 1.35 - n * 0.06);
  const bag: ZombieId[] = ["basic", "basic", "basic", "cone"];
  if (n >= 2) bag.push("cone", "newspaper");
  if (n >= 3) bag.push("bucket", "door");
  if (n >= 4) bag.push("pole");
  if (n >= 5) bag.push("football", "bucket");
  if (n >= 7) bag.push("football", "pole", "door");
  const g: Array<[ZombieId, number, number]> = [];
  const types: Record<string, number> = {};
  for (let i = 0; i < count; i++) {
    const id = bag[i % bag.length]!;
    types[id] = (types[id] ?? 0) + 1;
  }
  for (const [id, c] of Object.entries(types)) {
    g.push([id as ZombieId, c, gap]);
  }
  return compile([{ t: t0, flag: n % 2 === 0, huge: n > 0 && n % 3 === 0, g }]);
}

