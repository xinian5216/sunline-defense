type Wave = {
  t: number;
  flag?: boolean;
  huge?: boolean;
  g: Array<[ZombieId, number, number]>;
};

function compile(waves: Wave[]): SpawnEvent[] {
  const out: SpawnEvent[] = [];
  for (const w of waves) {
    if (w.flag) out.push({ t: w.t, type: "flag", row: -1, flag: true, huge: w.huge });
    let t = w.t + (w.flag ? 0.5 : 0);
    for (const [type, n, gap] of w.g) {
      for (let i = 0; i < n; i++) {
        out.push({ t, type, row: -1, huge: w.huge });
        t += gap;
      }
    }
  }
  out.sort((a, b) => a.t - b.t);
  return out;
}

